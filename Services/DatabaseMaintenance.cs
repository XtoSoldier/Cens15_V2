using System.Net.Mail;
using System.Text;
using CENS15_V2.Data;
using CENS15_V2.Entities;
using CENS15_V2.Helper;
using CENS15_V2.Models;
using Microsoft.EntityFrameworkCore;
using Npgsql;

namespace CENS15_V2.Services;

public sealed class DatabaseMaintenance(
    AppDbContext db,
    IConfiguration config,
    PasswordHasher hasher,
    CheckpointStorage storage,
    ILogger<DatabaseMaintenance> logger)
{
    // Consistency metadata is deliberately outside the restorable EF model.
    private const string LegacySchemaSql = """
        ALTER TABLE "CursadasMaterias" ADD COLUMN IF NOT EXISTS "MateriaNombre" text NOT NULL DEFAULT '';
        ALTER TABLE "Calificaciones" ADD COLUMN IF NOT EXISTS "MateriaNombre" text NOT NULL DEFAULT '';
        ALTER TABLE "Inscripciones" ADD COLUMN IF NOT EXISTS "CursoNombre" text NOT NULL DEFAULT '';
        ALTER TABLE "Inscripciones" ADD COLUMN IF NOT EXISTS "Division" text NOT NULL DEFAULT '';
        ALTER TABLE "Auths" ADD COLUMN IF NOT EXISTS "MustChangePassword" boolean NOT NULL DEFAULT false;
        ALTER TABLE "Auths" ADD COLUMN IF NOT EXISTS "InitialAccessSentAt" timestamp with time zone NULL;
        CREATE TABLE IF NOT EXISTS "LoginActivities" (
            "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            "CreatedAt" timestamp with time zone NOT NULL,
            "Email" text NOT NULL,
            "UserId" uuid NULL,
            "Success" boolean NOT NULL,
            "Reason" text NULL,
            "Platform" text NULL,
            "DeviceInfo" text NULL,
            "AppVersion" text NULL,
            "IpAddress" text NULL,
            CONSTRAINT "FK_LoginActivities_Users_UserId" FOREIGN KEY ("UserId") REFERENCES "Users" ("Id") ON DELETE SET NULL
        );
        CREATE INDEX IF NOT EXISTS "IX_LoginActivities_CreatedAt" ON "LoginActivities" ("CreatedAt");
        CREATE INDEX IF NOT EXISTS "IX_LoginActivities_Email" ON "LoginActivities" ("Email");
        CREATE INDEX IF NOT EXISTS "IX_LoginActivities_UserId" ON "LoginActivities" ("UserId");
        CREATE TABLE IF NOT EXISTS "PasswordResetCodes" (
            "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            "AuthId" uuid NOT NULL,
            "CodeHash" text NOT NULL,
            "CreatedAt" timestamp with time zone NOT NULL,
            "ExpiresAt" timestamp with time zone NOT NULL,
            "UsedAt" timestamp with time zone NULL,
            "Attempts" integer NOT NULL,
            CONSTRAINT "FK_PasswordResetCodes_Auths_AuthId" FOREIGN KEY ("AuthId") REFERENCES "Auths" ("Id") ON DELETE CASCADE
        );
        CREATE INDEX IF NOT EXISTS "IX_PasswordResetCodes_AuthId" ON "PasswordResetCodes" ("AuthId");
        CREATE INDEX IF NOT EXISTS "IX_PasswordResetCodes_ExpiresAt" ON "PasswordResetCodes" ("ExpiresAt");
        CREATE TABLE IF NOT EXISTS public."__CensCheckpointCommits" ("Id" uuid PRIMARY KEY);
        """;

    public async Task RunAsync(string operation, string expectedDatabase, CancellationToken ct = default)
    {
        if (operation is not ("migrate" or "seed"))
            throw new InvalidOperationException("Operacion de mantenimiento invalida; use migrate o seed.");
        if (string.IsNullOrWhiteSpace(expectedDatabase))
            throw new InvalidOperationException("La confirmacion de la base de datos es obligatoria.");

        NpgsqlConnectionStringBuilder configured;
        try
        {
            var value = config.GetConnectionString("DefaultConnection");
            if (string.IsNullOrWhiteSpace(value)) throw new ArgumentException();
            configured = new NpgsqlConnectionStringBuilder(value);
            if (string.IsNullOrWhiteSpace(configured.Host) || string.IsNullOrWhiteSpace(configured.Database))
                throw new ArgumentException();
        }
        catch
        {
            throw new InvalidOperationException("ConnectionStrings:DefaultConnection debe contener un destino PostgreSQL explicito y valido.");
        }

        if (db.Database.ProviderName != "Npgsql.EntityFrameworkCore.PostgreSQL" ||
            db.Database.GetDbConnection() is not NpgsqlConnection connection)
            throw new InvalidOperationException("El mantenimiento requiere el proveedor PostgreSQL Npgsql.");

        NpgsqlConnectionStringBuilder actual;
        try { actual = new NpgsqlConnectionStringBuilder(connection.ConnectionString); }
        catch { throw new InvalidOperationException("El destino PostgreSQL del contexto no es valido."); }
        if (string.IsNullOrWhiteSpace(connection.Database) ||
            !string.Equals(expectedDatabase, connection.Database, StringComparison.Ordinal) ||
            !string.Equals(configured.Database, connection.Database, StringComparison.Ordinal) ||
            !string.Equals(configured.Host, actual.Host, StringComparison.Ordinal) ||
            configured.Port != actual.Port || configured.Username != actual.Username)
            throw new InvalidOperationException("La confirmacion o configuracion no coincide con el destino PostgreSQL del contexto.");

        // The injected singleton holds instance.lock for the entire maintenance scope.
        var journal = Path.Combine(storage.Root, "restore.journal");
        CheckpointStorage.EnsureNoLinks(journal);
        if (File.Exists(journal) || Directory.Exists(journal))
            throw new InvalidOperationException("Existe restore.journal pendiente; no se permite mantenimiento antes de resolver la recuperacion.");

        try
        {
            ct.ThrowIfCancellationRequested();
            if (operation == "migrate")
            {
                await db.Database.MigrateAsync(ct);
                await db.Database.ExecuteSqlRawAsync(LegacySchemaSql, ct);
            }
            else
            {
                await SeedAsync(ct);
            }
            logger.LogInformation("Mantenimiento {Operation} completado correctamente.", operation);
        }
        catch (OperationCanceledException) when (ct.IsCancellationRequested)
        {
            throw new OperationCanceledException("Mantenimiento cancelado.", ct);
        }
        catch
        {
            // Provider exceptions can contain connection details or bootstrap values.
            logger.LogError("Fallo el mantenimiento {Operation}; no se completaron todas las operaciones.", operation);
            throw new InvalidOperationException("Fallo el mantenimiento de base de datos. Revise la configuracion y el estado del esquema antes de reintentar.");
        }
    }

    private async Task SeedAsync(CancellationToken ct)
    {
        var email = config["Bootstrap:AdminEmail"]?.Trim();
        var password = config["Bootstrap:AdminPassword"];
        var missingEmail = string.IsNullOrWhiteSpace(email);
        var missingPassword = string.IsNullOrWhiteSpace(password);
        if (missingEmail != missingPassword)
            throw new InvalidOperationException("Bootstrap requiere email y password juntos.");
        if (!missingEmail && (!MailAddress.TryCreate(email, out var address) || address.Address != email ||
            password!.Length < 6 || Encoding.UTF8.GetByteCount(password) > 72))
            throw new InvalidOperationException("Credenciales bootstrap invalidas: email valido y password de al menos 6 caracteres y hasta 72 bytes UTF-8.");

        var hasAdmin = await db.Users.AsNoTracking().AnyAsync(u => u.Status &&
            (u.Role.Name.Replace(" ", "").Trim().ToLower() == "admin" || u.Role.Name.Replace(" ", "").Trim().ToLower() == "superadmin"), ct);
        if (missingEmail && !hasAdmin)
            throw new InvalidOperationException("Se requieren credenciales bootstrap porque no existe un administrador activo.");

        var existing = !missingEmail && await db.Auths.AsNoTracking().AnyAsync(a => a.Email.Trim().ToLower() == email!.ToLower(), ct);
        if (existing && !hasAdmin)
            throw new InvalidOperationException("El email bootstrap ya existe y no hay administrador activo; no se modifican cuentas existentes.");

        string? hash = null;
        if (!missingEmail && !existing)
        {
            if (!int.TryParse(config["Security:BCryptWorkFactor"], out var cost) || cost is < 4 or > 31)
                throw new InvalidOperationException("Security:BCryptWorkFactor debe estar entre 4 y 31.");
            hash = hasher.Hash(password!);
        }

        // All catalog saves and the optional bootstrap account share one relational transaction.
        await using var transaction = db.Database.IsRelational() ? await db.Database.BeginTransactionAsync(ct) : null;
        await DbSeeder.SeedCatalogsAsync(db);
        ct.ThrowIfCancellationRequested();
        if (hash != null)
        {
            var adminRole = await db.Roles.FirstAsync(r => r.Name == "Admin", ct);
            var user = new User
            {
                Id = Guid.NewGuid(), FirstName = "Super", LastName = "Admin",
                Image = "default.png", RoleId = adminRole.Id, Status = true
            };
            db.AddRange(user, new Auth { Id = user.Id, Email = email!, PasswordHash = hash, User = user });
            await db.SaveChangesAsync(ct);
        }
        if (transaction != null) await transaction.CommitAsync(ct);
    }
}
